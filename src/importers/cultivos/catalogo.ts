/**
 * Catálogo curado de plantas cultivadas en Colombia: frutas, hortalizas y verduras,
 * cultivos de campo y flores.
 *
 * GBIF no clasifica las plantas por uso, así que esta lista es el criterio de qué entra.
 * Cada entrada se resuelve contra el Backbone de GBIF (nombre científico → especie aceptada),
 * de donde salen la taxonomía, los nombres comunes y las fotos con licencia abierta.
 *
 * Reglas de contenido (ver CONTENT_POLICY.md):
 * - Solo uso alimentario u ornamental. Nada medicinal ni ritual.
 * - Sin especies invasoras en Colombia (p. ej. Lantana camara, Pennisetum clandestinum).
 * - Sin cultivos de uso ilícito.
 *
 * `nombres` son nombres comunes usados en Colombia, escritos por el equipo del proyecto
 * (fuente: este catálogo, licencia ODbL). Están pendientes de revisión por agrónomos o botánicos.
 */

export type Categoria = 'FRUTA' | 'HORTALIZA' | 'CULTIVO' | 'FLOR';

export interface EntradaCatalogo {
  /** Nombre científico a buscar en GBIF. */
  cientifico: string;
  categorias: Categoria[];
  /** Nombres comunes en Colombia. */
  nombres?: string[];
}

const F = (cientifico: string, ...nombres: string[]): EntradaCatalogo => ({
  cientifico,
  categorias: ['FRUTA'],
  nombres,
});
const H = (cientifico: string, ...nombres: string[]): EntradaCatalogo => ({
  cientifico,
  categorias: ['HORTALIZA'],
  nombres,
});
const C = (cientifico: string, ...nombres: string[]): EntradaCatalogo => ({
  cientifico,
  categorias: ['CULTIVO'],
  nombres,
});
const L = (cientifico: string, ...nombres: string[]): EntradaCatalogo => ({
  cientifico,
  categorias: ['FLOR'],
  nombres,
});
const multi = (
  cientifico: string,
  categorias: Categoria[],
  ...nombres: string[]
): EntradaCatalogo => ({ cientifico, categorias, nombres });

